/**
 * Cryptographically secure random bytes.
 *
 * Every function here draws from the `node:crypto` CSPRNG and never
 * from `Math.random`. Binary output is a `Buffer` by default and
 * `hex`, `base64` or `base64url` text on request.
 */
import { randomBytes } from 'node:crypto';
import { encodeBytes } from '../../shared/encodings.ts';
import { InvalidArgumentError } from '../../shared/errors.ts';
import type { Encoding } from '../../shared/typings/encodings.js';

/**
 * Generates `length` cryptographically secure random bytes as a `Buffer`.
 *
 * @param length - Number of bytes to generate, a non-negative safe integer.
 * @returns A promise of a `Buffer` holding the bytes.
 * @throws {InvalidArgumentError} WHEN `length` is not a non-negative safe integer, delivered as a rejected promise.
 */
export function bytes(length: number): Promise<Buffer>;

/**
 * Generates `length` cryptographically secure random bytes as encoded text.
 *
 * @param length - Number of bytes to generate, a non-negative safe integer.
 * @param encoding - Output encoding: `hex`, `base64` or `base64url`.
 * @returns A promise of the encoded text, which decodes to `length` bytes.
 * @throws {InvalidArgumentError} WHEN `length` is not a non-negative safe integer or `encoding` is unsupported, delivered as a rejected promise.
 */
export function bytes(length: number, encoding: Encoding): Promise<string>;

export function bytes(
  length: number,
  encoding?: Encoding
): Promise<Buffer | string> {
  try {
    assertLength(length);
    assertEncoding(encoding);
  } catch (error: unknown) {
    if (error instanceof Error) {
      return Promise.reject(error);
    }
    return Promise.reject(invalidLengthError());
  }
  return new Promise<Buffer>(
    (
      resolve: (value: Buffer) => void,
      reject: (reason: unknown) => void
    ): void => {
      randomBytes(
        length,
        (error: Error | null | undefined, value: Buffer): void => {
          if (error) {
            reject(error);
            return;
          }
          resolve(value);
        }
      );
    }
  ).then(
    (value: Buffer): Buffer | string => render(value, encoding),
    (error: unknown): Buffer | string => {
      throw mapGeneratorError(error);
    }
  );
}

/**
 * Generates `length` cryptographically secure random bytes as a `Buffer`, synchronously.
 *
 * @param length - Number of bytes to generate, a non-negative safe integer.
 * @returns A `Buffer` holding the bytes.
 * @throws {InvalidArgumentError} WHEN `length` is not a non-negative safe integer.
 */
export function bytesSync(length: number): Buffer;

/**
 * Generates `length` cryptographically secure random bytes as encoded text, synchronously.
 *
 * @param length - Number of bytes to generate, a non-negative safe integer.
 * @param encoding - Output encoding: `hex`, `base64` or `base64url`.
 * @returns The encoded text, which decodes to `length` bytes.
 * @throws {InvalidArgumentError} WHEN `length` is not a non-negative safe integer or `encoding` is unsupported.
 */
export function bytesSync(length: number, encoding: Encoding): string;

export function bytesSync(
  length: number,
  encoding?: Encoding
): Buffer | string {
  assertLength(length);
  assertEncoding(encoding);
  try {
    return render(randomBytes(length), encoding);
  } catch (error: unknown) {
    throw mapGeneratorError(error);
  }
}

/**
 * Rejects lengths the CSPRNG cannot serve.
 *
 * @param length - Candidate byte count.
 * @throws {InvalidArgumentError} WHEN the count is not a non-negative safe integer.
 */
function assertLength(length: number): void {
  if (!Number.isSafeInteger(length) || length < 0) {
    throw invalidLengthError();
  }
}

/**
 * Output encodings the byte generator supports.
 */
const supportedEncodings: ReadonlySet<Encoding> = new Set<Encoding>([
  'hex',
  'base64',
  'base64url'
]);

/**
 * Rejects output encodings outside the shared closed set.
 *
 * @param encoding - Candidate output encoding, if one was given.
 * @throws {InvalidArgumentError} WHEN the encoding is not `hex`, `base64` or `base64url`.
 */
function assertEncoding(encoding: Encoding | undefined): void {
  if (encoding !== undefined && !supportedEncodings.has(encoding)) {
    throw new InvalidArgumentError(
      'Invalid encoding: expected hex, base64 or base64url.'
    );
  }
}

/**
 * Renders generated bytes as binary or text.
 *
 * @param value - Freshly generated bytes.
 * @param encoding - Output encoding, if one was requested.
 * @returns The bytes themselves, or their encoded text.
 */
function render(
  value: Buffer,
  encoding: Encoding | undefined
): Buffer | string {
  if (encoding === undefined) {
    return value;
  }
  return encodeBytes(value, encoding);
}

/**
 * Builds the fixed validation error for bad lengths.
 *
 * @returns The error, with no generated bytes in its message.
 */
function invalidLengthError(): InvalidArgumentError {
  return new InvalidArgumentError(
    'Invalid length: expected a non-negative safe integer.'
  );
}

/**
 * Keeps generator failures inside the stable error contract.
 *
 * Pre-validation rejects every servable length, so a `RangeError` here
 * only means the request exceeds the provider ceiling and becomes an
 * invalid length. Anything else is rethrown untouched.
 *
 * @param error - Failure escaped from `node:crypto`.
 * @returns The failure to throw, never the original `RangeError`.
 */
function mapGeneratorError(error: unknown): Error {
  if (error instanceof RangeError) {
    return invalidLengthError();
  }
  if (error instanceof Error) {
    return error;
  }
  return invalidLengthError();
}
